// Arabic counted noun for days: 1 يوم واحد · 2 يومان · 3 to 10 أيام · 11+ يوماً
const days = (n: number): string => {
  if (n === 1) return 'يوم واحد';
  if (n === 2) return 'يومان';
  if (n >= 3 && n <= 10) return `${n} أيام`;
  return `${n} يوماً`;
};

